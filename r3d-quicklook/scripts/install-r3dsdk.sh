#!/usr/bin/env bash
# Wires the RED R3D SDK (free download from https://www.red.com/developers) into the build so the
# Quick Look extensions can decode real frames instead of showing a clip card.
#
#   scripts/install-r3dsdk.sh ~/Downloads/R3DSDKv8_x_y
#
set -euo pipefail

SRC="${1:-}"
if [ -z "$SRC" ] || [ ! -d "$SRC" ]; then
  echo "usage: $0 /path/to/R3DSDK   (the unzipped SDK folder that contains Include/R3DSDK.h)" >&2
  exit 64
fi
SRC="$(cd "$SRC" && pwd)"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="$ROOT/Vendor/R3DSDK"

HEADER="$(find "$SRC" -name R3DSDK.h -not -path '*/__MACOSX/*' | head -n 1)"
[ -n "$HEADER" ] || { echo "error: R3DSDK.h not found under $SRC" >&2; exit 1; }

# Static loader library: prefer the libc++ build for macOS.
LIB="$(find "$SRC" -name 'libR3DSDK-libcpp.a' -path '*mac*' | head -n 1)"
[ -n "$LIB" ] || LIB="$(find "$SRC" -name 'libR3DSDK*.a' -path '*mac*' | head -n 1)"
[ -n "$LIB" ] || { echo "error: no macOS libR3DSDK*.a found under $SRC/Lib" >&2; exit 1; }

# Runtime decoder libraries (REDR3D.dylib and friends) that the SDK loads at runtime.
RUNTIME_LIB="$(find "$SRC" -name 'REDR3D*.dylib' -not -path '*/__MACOSX/*' | head -n 1)"
[ -n "$RUNTIME_LIB" ] || { echo "error: REDR3D*.dylib not found under $SRC/Redistributable" >&2; exit 1; }
RUNTIME_DIR="$(dirname "$RUNTIME_LIB")"

rm -rf "$DEST"
mkdir -p "$DEST/Include" "$DEST/Lib" "$DEST/Redistributable"
cp -R "$(dirname "$HEADER")/." "$DEST/Include/"
cp "$LIB" "$DEST/Lib/"
cp "$RUNTIME_DIR"/*.dylib "$DEST/Redistributable/"

LIBNAME="$(basename "$LIB" .a)"
LIBNAME="${LIBNAME#lib}"

cat > "$ROOT/Config/R3DSDK.local.xcconfig" <<XC
// Generated by scripts/install-r3dsdk.sh — do not commit.
R3DSDK_DIR = \$(PROJECT_DIR)/Vendor/R3DSDK
R3DSDK_REDIST_DIR = \$(R3DSDK_DIR)/Redistributable
HEADER_SEARCH_PATHS = \$(inherited) "\$(R3DSDK_DIR)/Include"
LIBRARY_SEARCH_PATHS = \$(inherited) "\$(R3DSDK_DIR)/Lib"
OTHER_LDFLAGS = \$(inherited) -l$LIBNAME -lc++ -framework CoreFoundation
OTHER_CFLAGS = \$(inherited) -DHAVE_R3DSDK=1
XC

echo "RED SDK installed into Vendor/R3DSDK:"
echo "  headers : $(dirname "$HEADER")"
echo "  library : $LIB"
echo "  runtime : $RUNTIME_DIR"
echo "Now run: make install"
